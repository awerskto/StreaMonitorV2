const STORAGE_KEY = 'sm.tube.language';

let current = 'en';

/** The code of the active language. */
export function getLanguage() {
    return current;
}

/** The messages of the active language, falling back to English. */
export function messages() {
    return MESSAGES[current] || MESSAGES.en;
}

/** Translate a key. `{0}`, `{1}` … are replaced by the arguments. */
export function t(key, ...args) {
    const text = messages()[key] ?? MESSAGES.en[key] ?? key;
    return text.replace(/\{(\d+)\}/g, (match, index) => {
        const value = args[Number(index)];
        return value === undefined ? match : String(value);
    });
}

/** The languages sorted by their own name, as the list shows them. */
export function languages() {
    return [...LANGUAGES].sort((a, b) => a.name.localeCompare(b.name, current));
}

export function languageByCode(code) {
    return LANGUAGES.find((language) => language.code === code) || null;
}

/** Switch the language and tell the application to draw itself again. */
export function setLanguage(code) {
    const language = languageByCode(code);
    current = language ? language.code : 'en';
    try {
        localStorage.setItem(STORAGE_KEY, current);
    } catch (error) {
        /* private mode */
    }
    // The module is imported by tests without a DOM as well.
    if (typeof document !== 'undefined') {
        document.documentElement.lang = current;
        document.dispatchEvent(new CustomEvent('sm:language'));
    }
    return current;
}

/** The saved language, or the one of the browser, or English. */
export function initLanguage() {
    let saved = null;
    try {
        saved = localStorage.getItem(STORAGE_KEY);
    } catch (error) {
        /* private mode */
    }
    if (saved && languageByCode(saved)) {
        current = saved;
    } else {
        // The browser may report pt-BR or nb-NO, the prefix is what counts.
        const spoken = (navigator.language || 'en').toLowerCase();
        const map = { 'pt-br': 'pt', nb: 'no', nn: 'no' };
        current = LANGUAGES.some((language) => language.code === spoken)
            ? spoken
            : (map[spoken] || map[spoken.split('-')[0]] || null)
              || (LANGUAGES.some((language) => language.code === spoken.split('-')[0])
                  ? spoken.split('-')[0] : 'en');
    }
    if (typeof document !== 'undefined') {
        document.documentElement.lang = current;
    }
    return current;
}
